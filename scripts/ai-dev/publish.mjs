import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { activity, jiraClient } from './jira.mjs';

function exec(command, args, env = process.env) {
  return execFileSync(command, args, { encoding: 'utf8', env, stdio: ['ignore', 'pipe', 'pipe'] }).trim();
}

async function main() {
  const task = JSON.parse(await readFile('.ai-dev/task.json', 'utf8'));
  const result = JSON.parse(await readFile('.ai-dev/result.json', 'utf8'));
  if (!result.ok) throw new Error('Refusing to publish an unsuccessful result');
  const env = { ...process.env, GH_TOKEN: process.env.AI_GITHUB_TOKEN };
  if (!env.GH_TOKEN) throw new Error('AI_GITHUB_TOKEN is required');
  exec('gh', ['auth', 'setup-git'], env);
  exec('git', ['config', 'user.name', 'BuddhaConnect AI Development']);
  exec('git', ['config', 'user.email', 'actions@users.noreply.github.com']);
  exec('git', ['add', '-A']);
  exec('git', ['commit', '-m', `feat(ai): implement ${task.key}`]);
  exec('git', ['push', '--set-upstream', 'origin', `HEAD:${task.branch}`], env);

  const type = task.type === 'Bug' ? 'fix' : 'feat';
  const cleanSummary = task.summary.replace(/^[^A-Za-z0-9]+/, '').slice(0, 90);
  const action = cleanSummary.charAt(0).toUpperCase() + cleanSummary.slice(1);
  const title = `[${type}][${task.key}] ${action}`;
  const tests = 'node --test tests/*.test.mjs; node scripts/check-repository.mjs; npm run check; npm run build';
  const body = [
    '## Jira / Scope', `- Jira ticket: ${task.key}`, '- Type: AI-assisted low-risk implementation', '',
    '## Implementation', `- ${task.summary}`, `- Changed files: ${result.assessment.files.join(', ')}`, '',
    '## Tests and evidence', `- Passed locally in the isolated runner: ${tests}`, `- Agent attempts: ${result.attempts.length}`, '',
    '## Risks and review', `- Automated risk result: ${result.assessment.lowRisk ? 'low-risk candidate' : 'manual merge required'}`,
    '- CI and branch protection remain authoritative; this PR has not been independently reviewed.',
    '- Production Publish is prohibited and is not part of this pipeline.', '',
    '## Configuration / limitations', '- Generated by the opt-in ai-ready pipeline using a repository-scoped credential and Gemini CLI.',
    '- UAT and Jira In QA updates occur only after merge and a verified GitHub Pages deployment.',
    `- Pipeline run: ${process.env.GITHUB_SERVER_URL}/${process.env.GITHUB_REPOSITORY}/actions/runs/${process.env.GITHUB_RUN_ID}`
  ].join('\n');
  await writeFile('.ai-dev/pr-body.md', body);
  for (const [name, color] of [['ai-generated', '5319e7'], [result.assessment.lowRisk ? 'risk:low' : 'risk:manual', result.assessment.lowRisk ? '0e8a16' : 'b60205'], ['ai-ci-retries:0', 'c5def5']]) {
    try { exec('gh', ['label', 'create', name, '--color', color, '--force'], env); } catch { /* Label may be managed by a ruleset. */ }
  }
  const prUrl = exec('gh', ['pr', 'create', '--base', 'master', '--head', task.branch, '--title', title, '--body-file', '.ai-dev/pr-body.md'], env);
  exec('gh', ['pr', 'edit', prUrl, '--add-label', `ai-generated,${result.assessment.lowRisk ? 'risk:low' : 'risk:manual'},ai-ci-retries:0`], env);
  const prNumber = exec('gh', ['pr', 'view', prUrl, '--json', 'number', '--jq', '.number'], env);
  const jira = jiraClient({ baseUrl: process.env.JIRA_BASE_URL, email: process.env.JIRA_EMAIL, apiToken: process.env.JIRA_API_TOKEN });
  await jira.comment(task.key, activity({
    action: 'Pull request created', summary: `Created PR #${prNumber} from isolated branch ${task.branch}.`,
    changes: `${result.assessment.files.length} files, ${result.assessment.totalLines} changed lines; risk candidate: ${result.assessment.lowRisk ? 'low' : 'manual review'}.`,
    testing: `${tests} — passed in the pipeline before push. GitHub required checks are pending.`, references: prUrl,
    nextStep: result.assessment.lowRisk ? 'Wait for all required checks; merge only if repository rules permit.' : 'Human approval is required before merge.'
  }));
  if (process.env.GITHUB_OUTPUT) await writeFile(process.env.GITHUB_OUTPUT, `pr_url=${prUrl}\npr_number=${prNumber}\nlow_risk=${result.assessment.lowRisk}\n`, { flag: 'a' });
  console.log(prUrl);
}

main().catch(error => { console.error(`Publish failed: ${error.message}`); process.exitCode = 1; });
